#!/usr/bin/env node
/**
 * Fails when a change hand-edits, or hand-publishes, the generated recipe data.
 *
 *   node scripts/check-generated-recipe-data.mjs <base-ref> [head-branch]
 *
 * Recipe metadata and taxonomy are authored in gleanwork/glean-cookbook at
 * recipes/<id>/recipe.json. This repo holds two derivatives:
 *
 *   data/cookbook-registry.json  a sync of that repo's built registry.json
 *   data/cookbook-taxonomy.json  capability/surface values and labels
 *   src/data/recipes.json        compiled from the sync by recipes:compile
 *
 * Both are committed, neither is gitignored, and JSON cannot carry a comment
 * saying so -- which is why four separate pull requests added recipes by editing
 * them directly. That looks completely correct: the build passes and the page
 * renders. The recipe then disappears on the next sync, because the sync writes
 * whatever upstream says and knows nothing about local additions.
 *
 * This check makes that failure immediate instead of a week later. It only fires
 * when the two files change without a matching lockstep regeneration, so a real
 * sync commit passes and a hand-edit does not.
 *
 * The second failure mode is a correctly generated sync carried here by hand,
 * usually alongside the cookbook PR that added the recipe. Nothing is wrong with
 * the data; it is just already the sync workflow's job, so the PR is redundant
 * and gets closed. Given <head-branch>, this refuses a branch other than the
 * sync workflow's that adds or removes a recipe. Reshaping existing entries (a
 * compiler change that emits a new field, say) still passes -- only the recipe
 * id set is owned by the sync.
 */

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const REGISTRY = 'data/cookbook-registry.json';
const TAXONOMY = 'data/cookbook-taxonomy.json';
const COMPILED = 'src/data/recipes.json';
const PAGES_DIR = 'docs/cookbook';
/** First line of every generated recipe page's frontmatter. */
const PAGE_MARKER = '# GENERATED by `pnpm registry:sync`';
/**
 * The branch .github/workflows/sync-cookbook-registry.yml pushes its generated
 * pull request to -- the only branch allowed to change which recipes exist here.
 */
const SYNC_BRANCH = 'ci/sync-cookbook-registry';

/** Listed recipe ids, in registry order. Hidden entries are never published here. */
function listedIds(registry) {
  return registry
    .filter((entry) => entry.hidden !== true)
    .map((entry) => entry.id);
}

export function publishedRecipeDrift(baseRegistry, headRegistry) {
  const before = new Set(listedIds(baseRegistry));
  const after = new Set(listedIds(headRegistry));
  return {
    added: [...after].filter((id) => !before.has(id)),
    removed: [...before].filter((id) => !after.has(id)),
  };
}

export function catalogIdDrift(registry, compiled) {
  const listedIds = new Set(
    registry.filter((entry) => entry.hidden !== true).map((entry) => entry.id),
  );
  const compiledIds = new Set(compiled.recipes.map((entry) => entry.id));
  const onlyCompiled = [...compiledIds].filter((id) => !listedIds.has(id));
  const onlyListed = [...listedIds].filter((id) => !compiledIds.has(id));
  return { listedCount: listedIds.size, onlyCompiled, onlyListed };
}

/**
 * Refuses a branch other than the sync workflow's that adds or removes a recipe.
 * Exits the process on failure; returns when the branch is allowed to do this.
 */
function checkSyncOwnership(base, headBranch, headRegistry) {
  if (!headBranch || headBranch === SYNC_BRANCH) return;

  let baseRegistry;
  try {
    baseRegistry = JSON.parse(
      execFileSync('git', ['show', `${base}:${REGISTRY}`], {
        encoding: 'utf8',
      }),
    );
  } catch {
    // No comparable base (shallow clone, or the file is new) — the hand-edit
    // checks above still ran, and guessing here would fail honest branches.
    return;
  }

  const { added, removed } = publishedRecipeDrift(baseRegistry, headRegistry);
  if (added.length === 0 && removed.length === 0) return;

  console.error(`
This branch publishes recipes by hand:

  added:   ${added.join(', ') || '(none)'}
  removed: ${removed.join(', ') || '(none)'}

Which recipes exist here is the sync workflow's output, not a pull request's. Every 15
minutes, sync-cookbook-registry regenerates ${REGISTRY}, ${PAGES_DIR}/<id>.mdx, ${COMPILED}
and the preview assets from gleanwork/glean-cookbook, then opens a PR that auto-merges.
Merging the recipe there is the whole of publishing it, so this branch duplicates work that
has already happened by the time anyone reviews it.

Drop the generated files and let the sync carry them:

  ${REGISTRY}
  ${COMPILED}
  ${PAGES_DIR}/<id>.mdx
  static/img/cookbook/previews/<id>/

Capabilities and surfaces are synced from the cookbook taxonomy and need no code here. If a
new category, status, or other value carries presentation behavior, keep only that consumer
code and its tests; drop everything generated.

To sync ahead of the schedule, run the workflow — Actions > Sync Cookbook Registry > Run
workflow — rather than committing its output.
`);
  process.exit(1);
}

function main() {
  const base = process.argv[2] ?? 'origin/main';
  // Empty on push builds, where the merged sync commit is legitimately in range.
  const headBranch = process.argv[3] ?? '';
  const repoRoot = path.resolve(import.meta.dirname, '..');

  function changed(file) {
    try {
      const out = execFileSync(
        'git',
        ['diff', '--name-only', `${base}...HEAD`, '--', file],
        {
          encoding: 'utf8',
        },
      );
      return out.trim().length > 0;
    } catch {
      return false;
    }
  }

  const pagesPath = path.join(repoRoot, PAGES_DIR);
  const unmarked = fs
    .readdirSync(pagesPath)
    .filter((file) => file.endsWith('.mdx') && file !== 'index.mdx')
    .filter(
      (file) =>
        !fs
          .readFileSync(path.join(pagesPath, file), 'utf8')
          .includes(PAGE_MARKER),
    );

  if (unmarked.length > 0) {
    console.error(`
These recipe pages are missing the generated-file marker, which means they were
written or edited here rather than upstream:

${unmarked.map((file) => `  ${PAGES_DIR}/${file}`).join('\n')}

Recipe prose lives in gleanwork/glean-cookbook at recipes/<id>/page.mdx, beside the
code it documents. Edit it there, then run \`pnpm registry:sync\` here — this
directory is generated, and a page added by hand is deleted by the next sync.
`);
    process.exit(1);
  }

  if (changed(TAXONOMY) && headBranch && headBranch !== SYNC_BRANCH) {
    let taxonomyExistsAtBase = true;
    try {
      // This initial bootstrap PR adds the snapshot before it exists on the
      // base branch. Once present, only the sync workflow owns its contents.
      execFileSync('git', ['show', `${base}:${TAXONOMY}`], {
        stdio: 'ignore',
      });
    } catch {
      taxonomyExistsAtBase = false;
    }
    if (taxonomyExistsAtBase) {
      console.error(`
${TAXONOMY} is generated by the scheduled cookbook sync. Define capabilities and surfaces
in gleanwork/glean-cookbook/config/recipe-taxonomy.json; do not edit the snapshot here.
`);
      process.exit(1);
    }
  }

  if (!changed(REGISTRY) && !changed(COMPILED)) {
    console.log('Generated recipe data untouched — nothing to check.');
    process.exit(0);
  }

  const registry = JSON.parse(
    fs.readFileSync(path.join(repoRoot, REGISTRY), 'utf8'),
  );
  const compiled = JSON.parse(
    fs.readFileSync(path.join(repoRoot, COMPILED), 'utf8'),
  );

  const { listedCount, onlyCompiled, onlyListed } = catalogIdDrift(
    registry,
    compiled,
  );

  if (onlyCompiled.length === 0 && onlyListed.length === 0) {
    console.log(
      `Generated recipe data changed and is self-consistent (${listedCount} listed recipes).`,
    );
    checkSyncOwnership(base, headBranch, registry);
    process.exit(0);
  }

  console.error(`
${REGISTRY} and ${COMPILED} disagree, which means one of them was edited by hand.

  only in ${COMPILED}: ${onlyCompiled.join(', ') || '(none)'}
  only listed in ${REGISTRY}:  ${onlyListed.join(', ') || '(none)'}

Listed recipes (hidden !== true) must match the compiled catalog. Hidden registry
entries must not appear in ${COMPILED}.

Both files are GENERATED. To add or change a recipe:

  1. Author recipes/<id>/recipe.json in gleanwork/glean-cookbook and run
     \`npm run build:registry\` there. That repo is the source of truth.
  2. Here, run \`pnpm registry:sync\` then \`pnpm recipes:compile\`.
  3. Add the prose page at docs/cookbook/<id>.mdx. It carries no metadata
     frontmatter -- it is matched to its registry entry by filename.

Editing these two files directly appears to work: the build passes and the page
renders. The recipe is then deleted by the next sync, which writes whatever
upstream says.
`);
  process.exit(1);
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  main();
}
