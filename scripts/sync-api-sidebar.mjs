#!/usr/bin/env node

/**
 * Validates and auto-fixes sidebars.ts against generated .api.mdx files.
 *
 * Usage:
 *   node scripts/sync-api-sidebar.mjs --check   CI gate: exits 1 if any .api.mdx
 *                                                file is missing from sidebars.ts,
 *                                                or if the Platform API Reference
 *                                                does not match the spec's
 *                                                x-tagGroups
 *   node scripts/sync-api-sidebar.mjs --fix     Inserts missing entries into
 *                                                sidebars.ts using the frontmatter
 *                                                from each .api.mdx file
 *
 * Files excluded from scanning:
 *   - overview.mdx / *-overview.mdx  (category overview pages, manually managed)
 *   - *.info.mdx                     (API info pages generated by openapi-docs)
 *   - *.tag.mdx                      (tag pages generated by openapi-docs)
 *
 * Platform API tag groups:
 *   When the Platform spec declares `x-tagGroups`, the Platform API Reference
 *   is grouped by them. Each group is an html sidebar item with
 *   `customProps.tagGroup` set to the group name, followed by one category
 *   per tag in that group. A category's tag is `customProps.tag`, or its label
 *   when `customProps.tag` is not set. Use `customProps.tag` when two
 *   families share a label, for example the Agents family in Agents & AI
 *   (tag `Agents`) and the Agents family in Administration (tag
 *   `Admin Agents`).
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { parseArgs } from 'node:util';
import jscodeshift from 'jscodeshift';
import * as prettier from 'prettier';
import * as yaml from 'js-yaml';

const j = jscodeshift.withParser('tsx');

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');
const DOCS_ROOT = path.join(REPO_ROOT, 'docs');
const SIDEBARS_PATH = path.join(REPO_ROOT, 'sidebars.ts');

const API_DIRS = [
  path.join(DOCS_ROOT, 'api/client-api'),
  path.join(DOCS_ROOT, 'api/indexing-api'),
  path.join(DOCS_ROOT, 'api/platform-api'),
];

const INDEXING_SPEC = path.join(
  REPO_ROOT,
  'openapi/indexing/indexing-capitalized.yaml',
);
const PLATFORM_SPEC = path.join(
  REPO_ROOT,
  'openapi/platform/platform-capitalized.yaml',
);
const CLIENT_SPLIT_DIR = path.join(REPO_ROOT, 'openapi/client/split-apis');
const HTTP_METHODS = ['get', 'post', 'put', 'patch', 'delete'];

function shouldSkip(filename) {
  return (
    filename === 'overview.mdx' ||
    filename.endsWith('-overview.mdx') ||
    filename.endsWith('.info.mdx') ||
    filename.endsWith('.tag.mdx')
  );
}

function parseFrontmatterField(yaml, name) {
  const re = new RegExp(`^${name}:\\s*"?([^"\\n]+?)"?\\s*$`, 'm');
  const m = yaml.match(re);
  return m ? m[1] : null;
}

function parseFrontmatter(content) {
  const match = content.match(/^---\n([\s\S]*?)\n---/);
  if (!match) return null;
  const yaml = match[1];

  const sidebarLabel =
    parseFrontmatterField(yaml, 'sidebar_label') ??
    parseFrontmatterField(yaml, 'title');
  const sidebarClassName = parseFrontmatterField(yaml, 'sidebar_class_name');

  // "post api-method" → "api-method post" (sidebar uses base-class-first order)
  const className = sidebarClassName
    ? sidebarClassName.split(' ').reverse().join(' ')
    : null;

  return { label: sidebarLabel, className };
}

function collectApiDocs(dir) {
  const results = [];
  if (!fs.existsSync(dir)) return results;

  for (const entry of fs
    .readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))) {
    if (entry.isDirectory()) {
      results.push(...collectApiDocs(path.join(dir, entry.name)));
    } else if (entry.name.endsWith('.api.mdx') && !shouldSkip(entry.name)) {
      const fullPath = path.join(dir, entry.name);
      const docId = path
        .relative(DOCS_ROOT, fullPath)
        .replace(/\.api\.mdx$/, '');
      const content = fs.readFileSync(fullPath, 'utf8');
      const frontmatter = parseFrontmatter(content);
      if (frontmatter) {
        results.push({ docId, filePath: fullPath, ...frontmatter });
      } else {
        console.warn(`Warning: could not parse frontmatter in ${fullPath}`);
      }
    }
  }
  return results;
}

function isOrphaned(docId) {
  const base = path.join(DOCS_ROOT, docId);
  return (
    !fs.existsSync(base + '.api.mdx') &&
    !fs.existsSync(base + '.mdx') &&
    !fs.existsSync(base + '-overview.mdx')
  );
}

function extractSidebarIds(root) {
  const ids = new Set();
  root
    .find(j.ObjectProperty, { key: { name: 'id' } })
    .filter((p) => {
      const v = p.node.value;
      return v.type === 'StringLiteral' && v.value.startsWith('api/');
    })
    .forEach((p) => ids.add(p.node.value.value));
  return ids;
}

function makeEntryNode(docId, label, className) {
  const props = [
    j.objectProperty(j.identifier('type'), j.stringLiteral('doc')),
    j.objectProperty(j.identifier('id'), j.stringLiteral(docId)),
    j.objectProperty(j.identifier('label'), j.stringLiteral(label)),
  ];
  if (className) {
    props.push(
      j.objectProperty(j.identifier('className'), j.stringLiteral(className)),
    );
  }
  return j.objectExpression(props);
}

function slugify(text) {
  return text
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

// Match docusaurus-plugin-openapi-docs / lodash kebabCase for operationId
// filenames (getAgent → get-agent). Plain slugify would collapse to getagent.
function kebabCase(text) {
  return text
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1-$2')
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .toLowerCase();
}

function addTagMapping(slugToTags, slug, tag) {
  const tags = slugToTags.get(slug) ?? new Set();
  tags.add(tag);
  slugToTags.set(slug, tags);
}

// Build a map: docId-slug -> tag-name from all OpenAPI source specs.
// Used to determine which sidebar category a flat-structured doc (e.g.
// indexing-api endpoints) belongs to, since the file path alone doesn't
// encode the category.
function buildSlugToTagMap() {
  const map = new Map();
  const specPaths = [];
  if (fs.existsSync(INDEXING_SPEC)) specPaths.push(INDEXING_SPEC);
  if (fs.existsSync(PLATFORM_SPEC)) specPaths.push(PLATFORM_SPEC);
  if (fs.existsSync(CLIENT_SPLIT_DIR)) {
    for (const f of fs.readdirSync(CLIENT_SPLIT_DIR)) {
      if (f.endsWith('.yaml')) specPaths.push(path.join(CLIENT_SPLIT_DIR, f));
    }
  }
  for (const specPath of specPaths) {
    let spec;
    try {
      spec = yaml.load(fs.readFileSync(specPath, 'utf8'));
    } catch (e) {
      console.warn(`Warning: failed to parse ${specPath}: ${e.message}`);
      continue;
    }
    for (const methods of Object.values(spec?.paths ?? {})) {
      if (!methods || typeof methods !== 'object') continue;
      for (const [m, op] of Object.entries(methods)) {
        if (!HTTP_METHODS.includes(m)) continue;
        if (!op || typeof op !== 'object') continue;
        const tag = op.tags?.[0];
        if (!tag) continue;
        if (op.operationId) {
          addTagMapping(map, op.operationId, tag);
          addTagMapping(map, kebabCase(op.operationId), tag);
        }
        if (op.summary) {
          addTagMapping(map, slugify(op.summary), tag);
        }
      }
    }
  }
  return map;
}

function getStringProperty(node, name) {
  const property = node.properties.find(
    (prop) =>
      prop.type === 'ObjectProperty' &&
      prop.key?.name === name &&
      prop.value?.type === 'StringLiteral',
  );
  return property?.value.value ?? null;
}

function getCustomPropsString(node, name) {
  const customProps = node.properties.find(
    (prop) =>
      prop.type === 'ObjectProperty' &&
      prop.key?.name === 'customProps' &&
      prop.value?.type === 'ObjectExpression',
  );
  const property = customProps?.value.properties.find(
    (prop) =>
      prop.type === 'ObjectProperty' &&
      (prop.key?.name === name || prop.key?.value === name) &&
      prop.value?.type === 'StringLiteral',
  );
  return property?.value.value ?? null;
}

function escapeHtml(text) {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

// The OpenAPI tag a Platform family category represents.
function getFamilyTag(node) {
  return getCustomPropsString(node, 'tag') ?? getStringProperty(node, 'label');
}

function isCategoryNode(node) {
  return (
    node?.type === 'ObjectExpression' &&
    getStringProperty(node, 'type') === 'category'
  );
}

function getTagGroupHeading(node) {
  if (
    node?.type !== 'ObjectExpression' ||
    getStringProperty(node, 'type') !== 'html'
  ) {
    return null;
  }
  return getCustomPropsString(node, 'tagGroup');
}

function isOpenApiSpecLink(node) {
  return (
    node?.type === 'ObjectExpression' &&
    getStringProperty(node, 'type') === 'link' &&
    getStringProperty(node, 'label') === 'OpenAPI Spec'
  );
}

function loadPlatformSpec() {
  if (!fs.existsSync(PLATFORM_SPEC)) return null;
  try {
    return yaml.load(fs.readFileSync(PLATFORM_SPEC, 'utf8'));
  } catch (e) {
    console.warn(`Warning: failed to parse ${PLATFORM_SPEC}: ${e.message}`);
    return null;
  }
}

// Returns [{ name, tags }] from the Platform spec's x-tagGroups, or null when
// the spec does not declare any.
function loadPlatformTagGroups(spec) {
  const groups = spec?.['x-tagGroups'];
  if (!Array.isArray(groups) || groups.length === 0) return null;
  return groups.map((group) => ({
    name: String(group.name),
    tags: (group.tags ?? []).map(String),
  }));
}

// Map each Platform doc slug to its operation's first tag, and collect every
// tag that an operation uses.
function loadPlatformOperationTags(spec) {
  const slugToTag = new Map();
  const usedTags = new Set();
  for (const methods of Object.values(spec?.paths ?? {})) {
    if (!methods || typeof methods !== 'object') continue;
    for (const [m, op] of Object.entries(methods)) {
      if (!HTTP_METHODS.includes(m) || !op || typeof op !== 'object') continue;
      const tag = op.tags?.[0];
      if (!tag) continue;
      usedTags.add(tag);
      if (op.operationId) {
        slugToTag.set(op.operationId, tag);
        slugToTag.set(kebabCase(op.operationId), tag);
      }
    }
  }
  return { slugToTag, usedTags };
}

function collectDocIds(node, ids = []) {
  const items = getItemsProperty(node);
  for (const element of items?.elements ?? []) {
    if (element?.type !== 'ObjectExpression') continue;
    const type = getStringProperty(element, 'type');
    const id = getStringProperty(element, 'id');
    if (type === 'doc' && id) ids.push(id);
    if (type === 'category') collectDocIds(element, ids);
  }
  return ids;
}

// Check that the Platform API Reference follows x-tagGroups: headings appear
// once each, in spec order; every family sits under the heading of its tag's
// group; and every operation sits in the family for its own tag.
function validatePlatformTagGroups(root, tagGroups, operationTags) {
  const errors = [];
  const groupOfTag = new Map();
  for (const group of tagGroups) {
    for (const tag of group.tags) groupOfTag.set(tag, group.name);
  }
  for (const tag of [...operationTags.usedTags].sort()) {
    if (!groupOfTag.has(tag)) {
      errors.push(
        `Platform tag '${tag}' is used by an operation but is not in any x-tagGroups entry`,
      );
    }
  }

  const reference = findReferenceItems(root, 'Platform API Reference');
  if (reference.error) {
    return [...errors, reference.error];
  }

  const groupOrder = tagGroups.map((group) => group.name);
  const seenGroups = new Set();
  let currentGroup = null;
  let lastGroupIndex = -1;
  for (const element of reference.items.elements) {
    const heading = getTagGroupHeading(element);
    if (heading !== null) {
      const index = groupOrder.indexOf(heading);
      if (index === -1) {
        errors.push(
          `Platform heading '${heading}' has no x-tagGroups entry with that name`,
        );
      } else if (seenGroups.has(heading)) {
        errors.push(`Platform heading '${heading}' appears more than once`);
      } else if (index < lastGroupIndex) {
        errors.push(
          `Platform heading '${heading}' is out of order; headings must follow x-tagGroups order (${groupOrder.join(', ')})`,
        );
      }
      const value = getStringProperty(element, 'value');
      if (value !== escapeHtml(heading)) {
        errors.push(
          `Platform heading '${heading}' must have value '${escapeHtml(heading)}', found '${value}'`,
        );
      }
      seenGroups.add(heading);
      lastGroupIndex = Math.max(lastGroupIndex, index);
      currentGroup = heading;
      continue;
    }
    if (!isCategoryNode(element)) continue;

    const label = getStringProperty(element, 'label');
    const tag = getFamilyTag(element);
    const expectedGroup = groupOfTag.get(tag);
    if (!expectedGroup) {
      errors.push(
        `Platform family '${label}' (tag '${tag}') is not in any x-tagGroups entry`,
      );
    } else if (currentGroup !== expectedGroup) {
      errors.push(
        `Platform family '${label}' (tag '${tag}') belongs under '${expectedGroup}', but sits under ${currentGroup ? `'${currentGroup}'` : 'no heading'}`,
      );
    }
    for (const docId of collectDocIds(element)) {
      const slug = docId.split('/').pop();
      const opTag = operationTags.slugToTag.get(slug);
      if (opTag && opTag !== tag) {
        errors.push(
          `'${docId}' has tag '${opTag}', but sits in Platform family '${label}' (tag '${tag}')`,
        );
      }
    }
  }
  for (const group of tagGroups) {
    const published = group.tags.some((tag) => operationTags.usedTags.has(tag));
    if (published && !seenGroups.has(group.name)) {
      errors.push(`Platform API Reference has no heading for '${group.name}'`);
    }
  }
  return errors;
}

function getItemsProperty(node) {
  const property = node.properties.find(
    (prop) =>
      prop.type === 'ObjectProperty' &&
      prop.key?.name === 'items' &&
      prop.value?.type === 'ArrayExpression',
  );
  return property?.value ?? null;
}

// Find the `items` array of the sidebar category whose label matches the
// given tag. Falls back to a `<tag> (...)` prefix match so a category can
// add a clarifying parenthetical (e.g. label "Custom Metadata (Any Datasource)"
// for OpenAPI tag "Custom Metadata") without breaking auto-insertion.
function findCategoryItemsByLabel(root, label) {
  let found = null;
  root.find(j.ObjectExpression).forEach((p) => {
    if (found) return;
    const props = p.node.properties;
    const isCategory = props.some(
      (pr) =>
        pr.type === 'ObjectProperty' &&
        pr.key?.name === 'type' &&
        pr.value?.type === 'StringLiteral' &&
        pr.value?.value === 'category',
    );
    if (!isCategory) return;
    const labelMatch = props.some(
      (pr) =>
        pr.type === 'ObjectProperty' &&
        pr.key?.name === 'label' &&
        pr.value?.type === 'StringLiteral' &&
        (pr.value.value === label || pr.value.value.startsWith(`${label} (`)),
    );
    if (!labelMatch) return;
    const itemsProp = props.find(
      (pr) => pr.type === 'ObjectProperty' && pr.key?.name === 'items',
    );
    if (itemsProp?.value?.type === 'ArrayExpression') {
      found = itemsProp.value;
    }
  });
  return found;
}

function findCategoriesByLabel(elements, label) {
  return elements.filter(
    (element) =>
      element?.type === 'ObjectExpression' &&
      getStringProperty(element, 'type') === 'category' &&
      getStringProperty(element, 'label') === label &&
      getItemsProperty(element),
  );
}

function findReferenceItems(root, referenceLabel) {
  const matches = [];
  root.find(j.ObjectExpression).forEach((path) => {
    if (
      getStringProperty(path.node, 'type') === 'category' &&
      getStringProperty(path.node, 'label') === referenceLabel
    ) {
      const items = getItemsProperty(path.node);
      if (items) {
        matches.push(items);
      }
    }
  });
  if (matches.length !== 1) {
    return {
      error: `expected one ${referenceLabel} category, found ${matches.length}`,
    };
  }
  return { items: matches[0] };
}

function resolveReferenceTarget(root, referenceLabel, tag) {
  const reference = findReferenceItems(root, referenceLabel);
  if (reference.error) {
    return reference;
  }
  const matches = findCategoriesByLabel(reference.items.elements, tag);
  if (matches.length !== 1) {
    return {
      error: `expected one ${referenceLabel} category labelled '${tag}', found ${matches.length}`,
    };
  }
  return { items: getItemsProperty(matches[0]) };
}

function resolveTag(slugToTags, slug) {
  const tags = slugToTags.get(slug);
  if (!tags) {
    return { error: `no OpenAPI tag found for slug '${slug}'` };
  }
  if (tags.size !== 1) {
    return {
      error: `ambiguous OpenAPI tags for slug '${slug}': ${[...tags].sort().join(', ')}`,
    };
  }
  return { tag: [...tags][0] };
}

function makeCategoryNode(label) {
  return j.objectExpression([
    j.objectProperty(j.identifier('type'), j.stringLiteral('category')),
    j.objectProperty(j.identifier('label'), j.stringLiteral(label)),
    j.objectProperty(j.identifier('items'), j.arrayExpression([])),
  ]);
}

// Remove sidebar entries whose `id` is in `orphanedIds` (typically because the
// upstream OpenAPI spec renamed or removed the operation, leaving the entry
// pointing at a doc that no longer exists). Operates on every `items: [...]`
// array in the AST so nested categories are handled.
function removeOrphanEntries(root, orphanedIds) {
  if (orphanedIds.size === 0) return 0;
  let removed = 0;
  root.find(j.ObjectProperty, { key: { name: 'items' } }).forEach((p) => {
    const arr = p.node.value;
    if (arr.type !== 'ArrayExpression') return;
    const before = arr.elements.length;
    arr.elements = arr.elements.filter((el) => {
      if (!el || el.type !== 'ObjectExpression') return true;
      const idProp = el.properties.find(
        (prop) =>
          prop.type === 'ObjectProperty' &&
          prop.key?.name === 'id' &&
          prop.value?.type === 'StringLiteral',
      );
      if (!idProp) return true;
      return !orphanedIds.has(idProp.value.value);
    });
    removed += before - arr.elements.length;
  });
  return removed;
}

function findOverviewTarget(root, overviewId) {
  let found = null;
  root
    .find(j.ObjectProperty, { key: { name: 'items' } })
    .filter((path) => {
      const items = path.node.value;
      if (items.type !== 'ArrayExpression') return false;
      return items.elements.some(
        (element) =>
          element?.type === 'ObjectExpression' &&
          getStringProperty(element, 'id') === overviewId,
      );
    })
    .forEach((path) => {
      if (!found) {
        found = path.node.value;
      }
    });
  return found;
}

// Plan a new family category for `tag` at the end of its tag group's section:
// before the next heading, or before the OpenAPI Spec link.
function planGroupedPlatformCategory(platformItems, tag, tagGroups) {
  const group = tagGroups.find((candidate) => candidate.tags.includes(tag));
  if (!group) {
    return {
      error: `Platform tag '${tag}' is not in any x-tagGroups entry`,
    };
  }
  const elements = platformItems.elements;
  const headingIndex = elements.findIndex(
    (element) => getTagGroupHeading(element) === group.name,
  );
  if (headingIndex === -1) {
    return {
      error: `Platform API Reference has no heading for tag group '${group.name}'; add an html item with customProps.tagGroup '${group.name}'`,
    };
  }
  const before = elements
    .slice(headingIndex + 1)
    .find(
      (element) =>
        getTagGroupHeading(element) !== null || isOpenApiSpecLink(element),
    );
  return { category: makeCategoryNode(tag), before: before ?? null };
}

function resolvePlatformTarget(root, tag, plannedCategories, tagGroups) {
  const platform = findReferenceItems(root, 'Platform API Reference');
  if (platform.error) {
    return platform;
  }
  const matches = platform.items.elements.filter(
    (element) =>
      isCategoryNode(element) &&
      getItemsProperty(element) &&
      getFamilyTag(element) === tag,
  );
  if (matches.length > 1) {
    return {
      error: `ambiguous Platform API Reference categories for tag '${tag}'`,
    };
  }
  if (matches.length === 1) {
    return { items: getItemsProperty(matches[0]) };
  }
  if (tagGroups) {
    if (!plannedCategories.has(tag)) {
      const plan = planGroupedPlatformCategory(platform.items, tag, tagGroups);
      if (plan.error) {
        return plan;
      }
      plannedCategories.set(tag, { ...plan, parentItems: platform.items });
    }
    return { items: getItemsProperty(plannedCategories.get(tag).category) };
  }
  if (tag !== 'Chat') {
    return { error: `no Platform API Reference category labelled '${tag}'` };
  }
  const openApiSpecIndexes = platform.items.elements
    .map((element, index) => ({ element, index }))
    .filter(
      ({ element }) =>
        element?.type === 'ObjectExpression' &&
        getStringProperty(element, 'type') === 'link' &&
        getStringProperty(element, 'label') === 'OpenAPI Spec',
    )
    .map(({ index }) => index);
  if (openApiSpecIndexes.length !== 1) {
    return {
      error: `expected one Platform OpenAPI Spec link, found ${openApiSpecIndexes.length}`,
    };
  }
  if (!plannedCategories.has(tag)) {
    const category = makeCategoryNode(tag);
    plannedCategories.set(tag, {
      category,
      before: platform.items.elements[openApiSpecIndexes[0]],
      parentItems: platform.items,
    });
  }
  return { items: getItemsProperty(plannedCategories.get(tag).category) };
}

function resolveEntry(root, doc, slugToTags, plannedCategories, tagGroups) {
  const segments = doc.docId.split('/');
  const overviewId = segments.slice(0, -1).join('/') + '/overview';
  const isPlatformDoc = doc.docId.startsWith('api/platform-api/');
  const isClientDoc = doc.docId.startsWith('api/client-api/');
  const isIndexingDoc = doc.docId.startsWith('api/indexing-api/');
  if (!isPlatformDoc && !isClientDoc && !isIndexingDoc) {
    const overviewTarget = findOverviewTarget(root, overviewId);
    if (overviewTarget) {
      return { items: overviewTarget };
    }
  }

  // Fallback: look up the operation's OpenAPI tag and find the category whose
  // label matches. This handles flat-structure APIs (e.g. indexing-api) where
  // all docs live in one directory and the category is determined by the tag,
  // not the file path.
  const slug = segments[segments.length - 1];
  const tagResult = resolveTag(slugToTags, slug);
  if (tagResult.error) {
    return tagResult;
  }
  if (isPlatformDoc) {
    return resolvePlatformTarget(
      root,
      tagResult.tag,
      plannedCategories,
      tagGroups,
    );
  }
  if (isClientDoc) {
    return resolveReferenceTarget(root, 'Client API Reference', tagResult.tag);
  }
  if (isIndexingDoc) {
    return resolveReferenceTarget(
      root,
      'Indexing API Reference',
      tagResult.tag,
    );
  }
  const items = findCategoryItemsByLabel(root, tagResult.tag);
  return items
    ? { items }
    : { error: `no sidebar category labelled '${tagResult.tag}'` };
}

const { values: args } = parseArgs({
  options: {
    check: { type: 'boolean', default: false },
    fix: { type: 'boolean', default: false },
  },
});

if (!args.check && !args.fix) {
  console.error('Usage: node scripts/sync-api-sidebar.mjs --check | --fix');
  process.exit(1);
}

const allDocs = API_DIRS.flatMap(collectApiDocs);
const sidebarSource = fs.readFileSync(SIDEBARS_PATH, 'utf8');
const root = j(sidebarSource);
const existingIds = extractSidebarIds(root);
const missing = allDocs.filter((d) => !existingIds.has(d.docId));
const orphaned = [...existingIds].filter(isOrphaned);
const platformSpec = loadPlatformSpec();
const platformTagGroups = loadPlatformTagGroups(platformSpec);

if (args.check) {
  let groupErrors = [];
  if (platformTagGroups) {
    groupErrors = validatePlatformTagGroups(
      root,
      platformTagGroups,
      loadPlatformOperationTags(platformSpec),
    );
  } else if (
    root
      .find(j.ObjectExpression)
      .filter((p) => getTagGroupHeading(p.node) !== null)
      .size() > 0
  ) {
    console.warn(
      'Warning: sidebars.ts has Platform tag group headings, but the Platform spec has no x-tagGroups to check them against.\n',
    );
  }
  if (groupErrors.length > 0) {
    console.error(
      `✗ The Platform API Reference does not match x-tagGroups (${groupErrors.length} problem(s)):\n`,
    );
    for (const error of groupErrors) {
      console.error(`  - ${error}`);
    }
    console.error('');
  }

  if (orphaned.length > 0) {
    console.warn(
      `Warning: ${orphaned.length} sidebar ID(s) have no corresponding .api.mdx file (investigate or clean up manually):`,
    );
    for (const id of orphaned) {
      console.warn(`  - ${id}`);
    }
    console.warn('');
  }

  if (missing.length === 0) {
    if (groupErrors.length > 0) {
      process.exit(1);
    }
    console.log('✓ sidebars.ts is complete — no missing API entries.');
    process.exit(0);
  }

  console.error(
    `✗ ${missing.length} .api.mdx file(s) are missing from sidebars.ts:\n`,
  );
  for (const doc of missing) {
    console.error(`  - ${doc.docId}`);
  }
  console.error(
    '\nRun `node scripts/sync-api-sidebar.mjs --fix` to auto-insert them.',
  );
  process.exit(1);
}

if (missing.length === 0 && orphaned.length === 0) {
  console.log('✓ sidebars.ts is already complete — nothing to do.');
  process.exit(0);
}

const failures = [];
const insertionPlans = [];
const plannedCategories = new Map();
const slugToTags = buildSlugToTagMap();

for (const doc of missing) {
  const target = resolveEntry(
    root,
    doc,
    slugToTags,
    plannedCategories,
    platformTagGroups,
  );
  if (target.error) {
    failures.push(`Could not auto-insert '${doc.docId}': ${target.error}`);
  } else {
    insertionPlans.push({ doc, items: target.items });
  }
}

if (failures.length > 0) {
  console.error(
    '\nThe following entries could not be auto-inserted; sidebars.ts was not changed:',
  );
  for (const failure of failures) {
    console.error(`  ! ${failure}`);
  }
  process.exit(1);
}

for (const { category, before, parentItems } of plannedCategories.values()) {
  const insertAt = before
    ? parentItems.elements.indexOf(before)
    : parentItems.elements.length;
  parentItems.elements.splice(insertAt, 0, category);
}
for (const { doc, items } of insertionPlans) {
  items.elements.push(makeEntryNode(doc.docId, doc.label, doc.className));
}

const orphanedSet = new Set(orphaned);
const removedCount = removeOrphanEntries(root, orphanedSet);

const transformed = root.toSource();
const prettierConfig = await prettier.resolveConfig(SIDEBARS_PATH);
const formatted = await prettier.format(transformed, {
  ...prettierConfig,
  filepath: SIDEBARS_PATH,
});
fs.writeFileSync(SIDEBARS_PATH, formatted, 'utf8');

if (missing.length > 0) {
  console.log(`✓ Inserted ${missing.length} entry(ies) into sidebars.ts:`);
  for (const doc of missing) {
    console.log(`  + ${doc.docId}  "${doc.label}"`);
  }
}

if (removedCount > 0) {
  console.log(
    `\n✓ Removed ${removedCount} orphan entry(ies) from sidebars.ts (no corresponding .api.mdx / .mdx file):`,
  );
  for (const id of orphaned) {
    console.log(`  - ${id}`);
  }
}
