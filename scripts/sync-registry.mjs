#!/usr/bin/env node

/**
 * Syncs the two artifacts the cookbook section is built from out of
 * gleanwork/glean-cookbook into committed local snapshots:
 *
 * - registry.json -> data/cookbook-registry.json (recipe metadata; the single
 *   source of truth, consumed by scripts/compile-recipes.ts)
 * - .claude-plugin/marketplace.json -> data/cookbook-plugin.json (the plugin's
 *   marketplace/plugin names, which the recipe pages print in install and
 *   invocation commands)
 *
 * The second exists so those names are never hardcoded here. They're what a
 * recipe page tells you to type -- `/plugin install <plugin>@<marketplace>`,
 * `/<plugin>:<recipe-id>` -- and the marketplace manifest is generated by
 * pluginpack from the plugin's own config, so renaming the plugin upstream can
 * no longer leave this site silently printing the old namespace.
 *
 * Mirrors scripts/openapi-capitalize-language.mjs's fetch-and-write shape:
 * fetched on demand (locally or in CI), never live during a build, and the
 * result is committed to git.
 *
 * Auth: in CI, set GITHUB_TOKEN to a short-lived GitHub App installation
 * token (see .github/workflows/sync-cookbook-registry.yml). Locally, falls
 * back to the invoking user's own `gh` auth so no token needs to be minted
 * by hand.
 *
 * Usage: node scripts/sync-registry.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const REPO = 'gleanwork/glean-cookbook';
const REGISTRY_PATH = 'registry.json';
// Claude Code's manifest specifically: all three targets carry the same
// marketplace and plugin names, and this one has the broadest schema.
const MARKETPLACE_PATH = '.claude-plugin/marketplace.json';
const repoRoot = path.resolve(import.meta.dirname, '..');
const registryFile = path.join(repoRoot, 'data', 'cookbook-registry.json');
const pluginFile = path.join(repoRoot, 'data', 'cookbook-plugin.json');

async function fetchViaToken(token, sourcePath) {
  const response = await fetch(
    `https://api.github.com/repos/${REPO}/contents/${sourcePath}`,
    {
      headers: {
        Authorization: `Bearer ${token}`,
        Accept: 'application/vnd.github.raw+json',
        'X-GitHub-Api-Version': '2022-11-28',
      },
    },
  );
  if (!response.ok) {
    throw new Error(
      `GitHub API request failed for ${sourcePath}: HTTP ${response.status} ${response.statusText}`,
    );
  }
  return response.text();
}

function fetchViaGhCli(sourcePath) {
  const base64 = execFileSync(
    'gh',
    ['api', `repos/${REPO}/contents/${sourcePath}`, '--jq', '.content'],
    { encoding: 'utf8' },
  )
    .trim()
    .split('\n')
    .join('');
  return Buffer.from(base64, 'base64').toString('utf8');
}

async function fetchSource(sourcePath) {
  if (process.env.GITHUB_TOKEN) {
    return fetchViaToken(process.env.GITHUB_TOKEN, sourcePath);
  }
  return fetchViaGhCli(sourcePath);
}

/**
 * Reduces the marketplace manifest to just what the site prints. Everything is
 * asserted rather than defaulted -- a missing field means the upstream manifest
 * changed shape, and guessing would put a wrong command on ten recipe pages.
 */
export function extractPluginCoordinates(raw) {
  const marketplace = JSON.parse(raw);
  const plugins = marketplace.plugins ?? [];
  if (plugins.length !== 1) {
    throw new Error(
      `Expected exactly 1 plugin in ${MARKETPLACE_PATH}, found ${plugins.length}. ` +
        `The site prints a single plugin namespace; teach it which one before adding more.`,
    );
  }

  const [plugin] = plugins;
  if (!marketplace.name || !plugin.name) {
    throw new Error(
      `${MARKETPLACE_PATH} is missing a marketplace name or plugin name.`,
    );
  }

  // The repo slug is what users type in `marketplace add`; take it from the
  // manifest's own repository URL rather than reusing REPO, so a move shows up
  // here instead of silently printing a stale path.
  const repositoryUrl = plugin.repository ?? '';
  const slug = repositoryUrl.match(/github\.com[/:]([^/]+\/[^/.]+)/)?.[1];
  if (!slug) {
    throw new Error(
      `Could not derive a GitHub slug from plugin.repository (${repositoryUrl || 'absent'}).`,
    );
  }

  return {
    marketplaceName: marketplace.name,
    pluginName: plugin.name,
    repo: slug,
  };
}

async function main() {
  console.log(`📡 Fetching ${REGISTRY_PATH} from ${REPO}...`);
  if (!process.env.GITHUB_TOKEN) {
    console.log(
      '💡 No GITHUB_TOKEN set — falling back to local `gh` CLI auth.',
    );
  }

  const rawRegistry = await fetchSource(REGISTRY_PATH);

  // Fail loudly on malformed content rather than committing garbage.
  const parsed = JSON.parse(rawRegistry);
  if (!Array.isArray(parsed)) {
    throw new Error('registry.json must be a JSON array of recipe entries.');
  }

  fs.mkdirSync(path.dirname(registryFile), { recursive: true });
  fs.writeFileSync(registryFile, `${JSON.stringify(parsed, null, 2)}\n`);
  console.log(
    `✅ Wrote ${parsed.length} recipe(s) to ${path.relative(repoRoot, registryFile)}`,
  );

  console.log(`📡 Fetching ${MARKETPLACE_PATH} from ${REPO}...`);
  const coordinates = extractPluginCoordinates(
    await fetchSource(MARKETPLACE_PATH),
  );
  fs.writeFileSync(pluginFile, `${JSON.stringify(coordinates, null, 2)}\n`);
  console.log(
    `✅ Wrote plugin coordinates (${coordinates.pluginName}@${coordinates.marketplaceName}) to ${path.relative(repoRoot, pluginFile)}`,
  );
}

// Only fetch when run as a script — the coordinate extraction below is
// imported directly by tests, which must not hit the network.
if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) {
  main().catch((error) => {
    console.error('❌', error.message);
    process.exit(1);
  });
}
